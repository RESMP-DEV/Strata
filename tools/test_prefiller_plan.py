TOOLS = Path(__file__).resolve().parent
SPEC = importlib.util.spec_from_file_location("prefiller_plan", TOOLS / "prefiller_plan.py")
MODULE = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(MODULE)


def write_trace(path: Path, rows: list[tuple[int, list[int], list[float]]]) -> None:
    with path.open("wb") as handle:
        for layer, ids, weights in rows:
            handle.write(struct.pack("<ii", layer, len(ids)))
            handle.write(struct.pack(f"<{len(ids)}i", *ids))
            handle.write(struct.pack(f"<{len(ids)}f", *weights))


def write_complete_trace(path: Path, overrides: dict[int, tuple[list[int], list[float]]]) -> None:
    rows: list[tuple[int, list[int], list[float]]] = []
    for layer in range(MODULE.N_LAYERS):
        if layer in overrides:
            ids, weights = overrides[layer]
        else:
            ids = list(range(500, 510))
            weights = [0.01] * 10
        rows.append((layer, ids, weights))
    write_trace(path, rows)


def write_inputs(
    root: Path, source: str = "Qwen3.8-Flash-Next-IQ2_XS-Q2_0.gguf"
) -> tuple[Path, Path]:
    index = root / "index.txt"
    rows: list[str] = ["output_hc_norm.weight 0 2 0 40960 0 40960 10240 0"]
    for layer in range(MODULE.N_LAYERS):
        prefix = f"blk.{layer}"
        suffixes: list[str] = []
        if layer < 36:
            suffixes.extend(MODULE.DENSE_ROLES["gdn_state"])
        if layer % 4 == 3:
            suffixes.extend(MODULE.DENSE_ROLES["qsa_state"])
        suffixes.extend(MODULE.DENSE_ROLES["hyper_connection"])
        suffixes.extend(MODULE.DENSE_ROLES["shared_expert"])
        for suffix in suffixes:
            shape = ROLE_SHAPES[suffix]
            rows.append(f"{prefix}{suffix} 0 0 0 0 0 0 {shape[0]} {shape[1]}")
    index.write_text(
        f"# strata pack index v3 -- generated by test from {source}\n"
        f"# align 64 pool 0 tensors {len(rows)}\n" + "\n".join(rows) + "\n",
        encoding="utf-8",
    )
    native = root / "native_experts.txt"
    native.write_text(
        "# strata native experts v4: layer gu_type d_type offset blob_bytes "
        f"gate_off up_off down_off (n_expert {MODULE.N_EXPERT}, "
        f"total {MODULE.N_LAYERS}; absolute)\n"
        + "\n".join(f"{layer} 17 42 {layer} 1 0 0 0" for layer in range(MODULE.N_LAYERS))
        + "\n",
        encoding="utf-8",
    )
    return index, native


ROLE_SHAPES = {
    ".attn_gate.weight": (2560, 6144),
    ".attn_qkv.weight": (2560, 10240),
    ".ssm_alpha.weight": (2560, 48),
    ".ssm_beta.weight": (2560, 48),
    ".ssm_out.weight": (6144, 2560),
    ".attn_k.weight": (2560, 512),
    ".attn_output.weight": (6144, 2560),
    ".attn_q.weight": (2560, 12288),
    ".attn_v.weight": (2560, 512),
    ".indexer.k_proj.weight": (2560, 128),
    ".indexer.q_proj.weight": (2560, 512),
    ".hc_attn_down.weight": (10240, 320),
    ".hc_attn_inject.weight": (10240, 4),
    ".hc_attn_up.weight": (320, 10240),
    ".hc_ffn_down.weight": (10240, 320),
    ".hc_ffn_inject.weight": (10240, 4),
    ".hc_ffn_up.weight": (320, 10240),
    ".ffn_gate_shexp.weight": (2560, 640),
    ".ffn_up_shexp.weight": (2560, 640),
    ".ffn_down_shexp.weight": (640, 2560),
}


class PrefillerPlanTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()  # pylint: disable=consider-using-with
        self.root = Path(self.temp.name)

    def tearDown(self) -> None:
        self.temp.cleanup()

    def test_dense_geometry_and_exact_mxfp4_bytes(self) -> None:
        index, native = write_inputs(self.root)
        _, shapes, tensor_count = MODULE.read_pack_index(index)
        self.assertEqual(tensor_count, len(shapes))
        dense = MODULE.dense_tensors(shapes)
        self.assertEqual(len(dense), 684)
        self.assertEqual(sum(item.elements for item in dense), 3_571_384_320)
        self.assertEqual(MODULE.mxfp4_bytes(3_571_384_320), 1_897_297_920)
        self.assertAlmostEqual(MODULE.mxfp4_bytes(3_571_384_320) / 2**30, 1.7669963836669922)

    def test_trace_selection_fill_and_coverage(self) -> None:
        index, native = write_inputs(self.root)
        trace = self.root / "route.bin"
        write_complete_trace(
            trace,
            {
                0: (
                    [3, 1, 2, 100, 101, 102, 103, 104, 105, 106],
                    [0.1, 0.6, 0.3, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01],
                ),
                1: (
                    [4, 5, 100, 101, 102, 103, 104, 105, 106, 107],
                    [0.2, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01],
                ),
            },
        )
        out = self.root / "plan.json"
        result = subprocess.run(
            [
                sys.executable,
                str(TOOLS / "prefiller_plan.py"),
                "--index",
                str(index),
                "--native-experts",
                str(native),
                str(trace),
                "--hot-experts",
                "2",
                "--out",
                str(out),
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        manifest = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual(manifest["expert_selection"]["selected_ids"][0], [1, 2])
        self.assertEqual(manifest["expert_selection"]["selected_ids"][1][:2], [4, 5])
        self.assertIsNotNone(manifest["expert_selection"]["aggregate_positive_weight_coverage"])
        self.assertEqual(manifest["target"]["model"], "Qwen3.8-Flash-Next")
        coverage = MODULE.expert_coverage(
            [[1, 2], [4]],
            {
                (0, 1): Fraction(6, 10),
                (0, 2): Fraction(3, 10),
                (0, 3): Fraction(1, 10),
                (1, 4): Fraction(2, 10),
            },
        )
        assert coverage is not None
        self.assertEqual(coverage[0] / coverage[1], Fraction(11, 12))

    def test_profile_only_has_deterministic_selection_and_null_coverage(self) -> None:
        index, native = write_inputs(self.root)
        profile = self.root / "profile.bin"
        ranked = [
            (layer, (7 + row) % MODULE.N_EXPERT)
            for layer in range(MODULE.N_LAYERS)
            for row in range(MODULE.N_EXPERT)
        ]
        MODULE.make_profile.write_profile(profile, ranked, MODULE.N_EXPERT)
        out = self.root / "plan.json"
        result = subprocess.run(
            [
                sys.executable,
                str(TOOLS / "prefiller_plan.py"),
                "--index",
                str(index),
                "--native-experts",
                str(native),
                "--profile",
                str(profile),
                "--hot-experts",
                "2",
                "--out",
                str(out),
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        manifest = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual(manifest["expert_selection"]["selected_ids"][0], [7, 8])
        self.assertIsNone(manifest["expert_selection"]["aggregate_positive_weight_coverage"])
        self.assertEqual(manifest["expert_selection"]["basis"], "profile_rank")

    def test_27b_template_is_refused_as_runtime_decoder(self) -> None:
        index, native = write_inputs(self.root, "Qwen3.8-27B-NVFP4-prefiller-00001-of-00064.gguf")
        with self.assertRaisesRegex(ValueError, "template, not a runtime dependency"):
            MODULE.read_pack_index(index)

    def test_offsetting_dense_shape_corruption_is_rejected(self) -> None:
        index, _ = write_inputs(self.root)
        _, shapes, _ = MODULE.read_pack_index(index)
        shapes["blk.3.attn_q.weight"] = (2560, 12289)
        with self.assertRaisesRegex(ValueError, "blk.3.attn_q.weight shape"):
            MODULE.dense_tensors(shapes)

    def test_invalid_router_weight_is_rejected_and_output_is_atomic(self) -> None:
        index, native = write_inputs(self.root)
        trace = self.root / "route.bin"
        trace.write_bytes(
            struct.pack("<ii", 0, 10)
            + struct.pack("<10i", *range(10))
            + struct.pack("<9f", *([0.1] * 9))
            + struct.pack("<f", float("nan"))
        )
        out = self.root / "plan.json"
        out.write_text("previous\n", encoding="utf-8")
        result = subprocess.run(
            [
                sys.executable,
                str(TOOLS / "prefiller_plan.py"),
                "--index",
                str(index),
                "--native-experts",
                str(native),
                str(trace),
                "--out",
                str(out),
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("invalid router weight", result.stderr)
        self.assertEqual(out.read_text(encoding="utf-8"), "previous\n")
        self.assertFalse(list(self.root.glob(".plan.json.*.tmp")))

    def test_zero_weight_is_rejected_weighted_and_counted_unweighted(self) -> None:
        trace = self.root / "serve.bin"
        write_complete_trace(trace, {0: ([1, *range(100, 109)], [0.0, *([0.1] * 9)])})
        with self.assertRaisesRegex(ValueError, "zero router weight.*--unweighted"):
            MODULE.read_trace_scores_exact([trace], weighted=True)
        unweighted, _ = MODULE.read_trace_scores_exact([trace], weighted=False)
        self.assertEqual(unweighted[(0, 1)], 1)

    def test_dense_only_manifest_is_allowed(self) -> None:
        index, native = write_inputs(self.root)
        trace = self.root / "route.bin"
        write_complete_trace(trace, {})
        out = self.root / "plan.json"
        result = subprocess.run(
            [
                sys.executable,
                str(TOOLS / "prefiller_plan.py"),
                "--index",
                str(index),
                "--native-experts",
                str(native),
                str(trace),
                "--hot-experts",
                "0",
                "--out",
                str(out),
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        manifest = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual(manifest["mxfp4_estimate"]["selected_expert_bytes"], 0)
        self.assertEqual(
            manifest["mxfp4_estimate"]["total_bytes"],
            manifest["mxfp4_estimate"]["dense_bytes"],
        )


if __name__ == "__main__":
    unittest.main()
